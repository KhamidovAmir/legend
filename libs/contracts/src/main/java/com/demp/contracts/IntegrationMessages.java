package com.demp.contracts;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import java.time.Instant;
import java.util.Map;
import java.util.UUID;

/** Commands/queries accepted and events published by integration-service. */
public final class IntegrationMessages {

    public static final String EXECUTE_ACTION = "ExecuteAction";
    public static final String QUERY_EXTERNAL_STATE = "QueryExternalState";

    public static final String ACCEPTED = "IntegrationAccepted";
    public static final String COMPLETED = "IntegrationCompleted";
    public static final String FAILED = "IntegrationFailed";
    public static final String UNKNOWN = "IntegrationUnknown";
    public static final String STATE_RECEIVED = "ExternalStateReceived";
    public static final String STATE_QUERY_FAILED = "ExternalStateQueryFailed";

    /**
     * @param operationId    generated by Resolution Service, so redelivery never creates a second operation
     * @param idempotencyKey key of the business attempt (ActionAttempt); forwarded to the external system
     */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record ExecuteAction(UUID operationId, UUID exceptionId, UUID actionId, UUID attemptId,
                                String targetSystem, String actionType, String entityType, String entityId,
                                String idempotencyKey, Map<String, String> params) {
    }

    @JsonIgnoreProperties(ignoreUnknown = true)
    public record QueryExternalState(UUID queryId, UUID exceptionId, String targetSystem, String entityType,
                                     String entityId, String purpose) {
    }

    @JsonIgnoreProperties(ignoreUnknown = true)
    public record IntegrationAccepted(UUID operationId, UUID exceptionId, String targetSystem,
                                      String externalRequestId) {
    }

    @JsonIgnoreProperties(ignoreUnknown = true)
    public record IntegrationCompleted(UUID operationId, UUID exceptionId, String targetSystem, String result) {
    }

    /** The command was definitely NOT applied by the external system. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record IntegrationFailed(UUID operationId, UUID exceptionId, String targetSystem, String reason,
                                    boolean retryable) {
    }

    /** The request may or may not have reached the external system. Never retried blindly. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record IntegrationUnknown(UUID operationId, UUID exceptionId, String targetSystem, String reason) {
    }

    /** An observation only: Integration does not decide whether the action was applied. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record ExternalStateReceived(UUID queryId, UUID exceptionId, String targetSystem, boolean found,
                                        String state, Instant observedAt) {
    }

    @JsonIgnoreProperties(ignoreUnknown = true)
    public record ExternalStateQueryFailed(UUID queryId, UUID exceptionId, String targetSystem, String reason) {
    }

    /**
     * Async result sent by Delivery team to {@link Topics#EXTERNAL_DELIVERY_RESULTS} (their format).
     * idempotencyKey echoes the key we sent: the only way to match a result of a command whose HTTP response was lost.
     */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record ExternalCommandResult(String externalRequestId, String idempotencyKey, String status, String result) {
    }

    private IntegrationMessages() {
    }
}
